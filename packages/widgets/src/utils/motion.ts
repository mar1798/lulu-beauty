import type { Transition } from 'motion/react'

/**
 * Общие тайминги анимаций. Заведены отдельным модулем, чтобы модалка,
 * подтверждение и уведомления двигались одинаково: разнобой в 50 мс между
 * соседними слоями заметен, а искать его потом по десяти компонентам дорого.
 *
 * Пружины — для того, что «прилетает» (диалог, тост): их можно прервать
 * повторным действием, и они доигрывают без рывка. Затемнение фона — обычный
 * тween: прозрачность физики не изображает, а пружина на ней даёт мигание.
 */

/** Затемнение под модалкой. */
export const OVERLAY_TRANSITION: Transition = { duration: 0.18, ease: 'easeOut' }

/** Появление окна диалога. `bounce` низкий: это не игровой интерфейс. */
export const DIALOG_TRANSITION: Transition = {
  type: 'spring',
  bounce: 0.15,
  visualDuration: 0.28,
}

/** Выезд уведомления. Чуть живее диалога — оно не требует внимания. */
export const TOAST_TRANSITION: Transition = {
  type: 'spring',
  bounce: 0.2,
  visualDuration: 0.32,
}
