import type { Transition } from 'motion/react'

/**
 * Общие тайминги анимаций. Заведены отдельным модулем, чтобы модалка,
 * подтверждение и уведомления двигались одинаково: разнобой в 50 мс между
 * соседними слоями заметен, а искать его потом по десяти компонентам дорого.
 *
 * Пружины — для того, что «прилетает» (диалог, тост): их можно прервать
 * повторным действием, и они доигрывают без рывка. Затемнение фона — обычный
 * тween: прозрачность физики не изображает, а пружина на ней даёт мигание.
 */

/** Затемнение под модалкой. */
export const OVERLAY_TRANSITION: Transition = { duration: 0.18, ease: 'easeOut' }

/** Появление окна диалога. `bounce` низкий: это не игровой интерфейс. */
export const DIALOG_TRANSITION: Transition = {
  type: 'spring',
  bounce: 0.15,
  visualDuration: 0.28,
}

/**
 * Раскрытие выпадающего списка. Заметно быстрее диалога и почти без отскока:
 * список открывается в ответ на клик и человек уже ведёт к нему курсор —
 * любая задержка и болтание читаются как «залипло». Пружина, а не tween,
 * потому что список закрывают повторным кликом, не дождавшись конца
 * анимации: прерванная пружина доигрывает от текущей точки без рывка.
 */
export const POPOVER_TRANSITION: Transition = {
  type: 'spring',
  bounce: 0.08,
  visualDuration: 0.18,
}

/** Насколько список смещён к полю до раскрытия. */
export const POPOVER_OFFSET = 6

/** Выезд уведомления. Чуть живее диалога — оно не требует внимания. */
export const TOAST_TRANSITION: Transition = {
  type: 'spring',
  bounce: 0.2,
  visualDuration: 0.32,
}

/**
 * Появление содержимого на месте скелетона (сетка товаров, список заявок,
 * сообщение об ошибке).
 *
 * Здесь именно tween, а не пружина: пружина изображает физику предмета,
 * который куда-то летит, а тут ничего не летит — блок просто проявляется.
 * Длительность короткая: анимация не должна задерживать чтение того, чего
 * человек и так уже подождал.
 */
export const APPEAR_DURATION_MS = 220

export const APPEAR_TRANSITION: Transition = {
  duration: APPEAR_DURATION_MS / 1000,
  ease: 'easeOut',
}

/** Насколько блок приподнят до появления. Больше — и это уже «выезд», а не проявление. */
export const APPEAR_OFFSET = 8

/* --- Главная: выход героя и появление секций по входу в вьюпорт --- */

/**
 * Вход секции главной (`Reveal`). Медленнее `APPEAR_TRANSITION`: тот гасит
 * подмену скелетона, которую человек уже подождал, а здесь блок приходит в
 * кадр на скролле, и за 220 мс движение просто не успевает прочитаться.
 * Tween, а не пружина — блок проявляется на месте, физику ему изображать
 * нечего.
 */
export const REVEAL_TRANSITION: Transition = { duration: 0.55, ease: 'easeOut' }

/**
 * Насколько блок приподнят до входа. Заметно больше `APPEAR_OFFSET`: у входа
 * по вьюпорту сдвиг — часть смысла («страница продолжается снизу»), а не
 * только смягчение подмены.
 */
export const REVEAL_OFFSET = 24

/** Шаг лесенки между соседними детьми секции (карточки, плитки, строки FAQ). */
export const REVEAL_STAGGER_STEP = 0.07

/**
 * Потолок лесенки в элементах: дальше задержка не растёт. Без него хвост
 * длинной сетки появлялся бы через секунды после входа в кадр — это читается
 * не как ритм, а как подвисание.
 */
export const REVEAL_STAGGER_LIMIT = 8

/*
 * Выход героя живёт в CSS (см. `HomeHero.css.ts`), а не в motion: как и у
 * `Appear`, анимация обязана начинаться с первой отрисовки статической
 * страницы, а не после гидратации — иначе первый экран приезжает с невидимым
 * заголовком и ждёт JS. Поэтому константы героя — миллисекунды и строки
 * easing, пригодные для CSS.
 */

/**
 * Выход строки заголовка из-под маски. Единственная «авторская» анимация
 * страницы, поэтому дольше служебных: строка едет весь свой кегль
 * (`translateY(100% → 0)`), и короткий tween превратил бы приём в дёрганье.
 */
export const HERO_LINE_DURATION_MS = 800

/**
 * Резкий разгон с длинным доводом (easeOutQuint) — классика типографских
 * масок: буквы «встают» без отскока.
 */
export const HERO_LINE_EASING = 'cubic-bezier(0.22, 1, 0.36, 1)'

/** Задержка между соседними ступенями лесенки героя (строки, описание, кнопки). */
export const HERO_STAGGER_STEP_MS = 120

/**
 * Проявление фоновых пятен героя: начинается сразу, идёт дольше заголовка
 * (`scale(1.06 → 1)` + прозрачность), чтобы к концу выхода текста фон уже
 * стоял на месте и в движении не участвовал.
 */
export const HERO_DECOR_DURATION_MS = 1400

/** Период зацикленного покачивания индикатора прокрутки. */
export const HERO_HINT_LOOP_DURATION_MS = 1800

/** Амплитуда покачивания индикатора, px: движение-намёк, а не прыжки. */
export const HERO_HINT_OFFSET = 6

/* --- Главная, ревизия 2: три слоя движения пятен и уход героя --- */

/**
 * Амплитуда скролл-параллакса пятна при `depth: 1`, px. В пикселях, а не в
 * процентах высоты картинки: процент вместе с процентной шириной давал
 * неограниченный ход на широком экране, и баночка резалась. 72 — предел,
 * при котором половина самого крупного пятна плюс весь ход укладываются в
 * `min-height` секции с пятнами.
 */
export const DECOR_PARALLAX_PX = 72

/**
 * Амплитуда непрерывной левитации баночки, px. Это дыхание, а не качели:
 * больше десятка пикселей — и пятно начинает спорить с контентом за взгляд.
 */
export const DECOR_FLOAT_OFFSET = 8

/**
 * Базовый период левитации. Медленнее любого жеста человека — движение
 * должно замечаться боковым зрением, а не следиться глазом. Реальный период
 * пятна разводится от базового его `floatPhase` (см. `DecorField`), чтобы
 * соседние пятна не качались в такт.
 */
export const DECOR_FLOAT_DURATION_MS = 7200

/**
 * Период встречного дрейфа ореола. Заметно длиннее левитации и не кратен ей:
 * расхождение частот двух слоёв и читается как глубина — синхронные слои
 * слипаются в один.
 */
export const HALO_FLOAT_DURATION_MS = 12800

/**
 * Амплитуды двух слоёв ухода героя при прокрутке, px. Заголовочный блок
 * едет быстрее нижней строки с кнопками и панелью — разница скоростей и
 * даёт ощущение, что страница вылезает из-под героя; один слой, как в
 * первой редакции, читался как «картинка едет».
 */
export const HERO_RISE_TITLE = 96

export const HERO_RISE_BOTTOM = 44

/**
 * Пульсация живой точки `StatusPanel`. Два такта в секунду — уже тревога;
 * ~2 с с `ease-in-out` читается как спокойное «сбор идёт прямо сейчас».
 */
export const STATUS_PULSE_DURATION_MS = 2000

/**
 * «Поп» финальных деталей мини-сцен шагов (пилюля «+1», галочка
 * подтверждения). Пружина, потому что деталь «прилетает» в макет; `bounce`
 * низкий — по той же причине, что у диалога: интерфейс не игровой.
 */
export const SCENE_POP_TRANSITION: Transition = {
  type: 'spring',
  bounce: 0.2,
  visualDuration: 0.3,
}

/**
 * Задержка элемента в лесенке появления по его индексу — с потолком: после
 * `REVEAL_STAGGER_LIMIT`-го элемента задержка перестаёт расти. Одна функция
 * на все секции, чтобы плитки, карточки и строки FAQ шли одним ритмом.
 */
export const staggerDelay = (index: number): number =>
  Math.min(index, REVEAL_STAGGER_LIMIT) * REVEAL_STAGGER_STEP

/**
 * Раскрытие ответа FAQ. Анимируется высота (осознанное исключение — см.
 * `FaqAccordion`), поэтому tween с symmetric-кривой: пружина на layout-свойстве
 * дёргала бы соседние строки, а easeInOut одинаково честно играет и раскрытие,
 * и сворачивание.
 */
export const FAQ_TRANSITION: Transition = { duration: 0.3, ease: [0.4, 0, 0.2, 1] }
