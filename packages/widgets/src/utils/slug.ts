/**
 * Адрес товара или категории из названия.
 *
 * Бэкенд требует `^[a-z0-9]+(-[a-z0-9]+)*$` (`SLUG_PATTERN` в
 * `apps/api/app/catalog/schemas.py`), а названия в магазине русские, поэтому
 * без транслитерации владельцу пришлось бы придумывать латиницу вручную для
 * каждого товара. Таблица — практическая, а не ГОСТ: важно, чтобы адрес
 * читался, а не чтобы его можно было развернуть обратно.
 */

const LETTERS: Record<string, string> = {
  а: 'a',
  б: 'b',
  в: 'v',
  г: 'g',
  д: 'd',
  е: 'e',
  ё: 'e',
  ж: 'zh',
  з: 'z',
  и: 'i',
  й: 'y',
  к: 'k',
  л: 'l',
  м: 'm',
  н: 'n',
  о: 'o',
  п: 'p',
  р: 'r',
  с: 's',
  т: 't',
  у: 'u',
  ф: 'f',
  х: 'h',
  ц: 'ts',
  ч: 'ch',
  ш: 'sh',
  щ: 'sch',
  ъ: '',
  ы: 'y',
  ь: '',
  э: 'e',
  ю: 'yu',
  я: 'ya',
}

export const slugify = (value: string): string => {
  const transliterated = Array.from(value.toLowerCase())
    .map(char => LETTERS[char] ?? char)
    .join('')

  return (
    transliterated
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-+|-+$/g, '')
      .slice(0, 255)
      // Ещё раз после обрезки: `slice` режет по символу и может оставить дефис
      // последним — а такой slug не проходит валидацию ни на форме, ни на бэкенде,
      // хотя поле выглядит заполненным правильно (на длинных русских названиях это
      // примерно каждый восьмой).
      .replace(/-+$/, '')
  )
}
