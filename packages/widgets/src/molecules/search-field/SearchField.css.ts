import { style } from '@vanilla-extract/css'
import { calc } from '@vanilla-extract/css-utils'
import { color, media, rem } from '../../styling/lib'
import { vars } from '../../styling/themes/contract.css'

/**
 * До `md` поле тянется во всю ширину: там оно стоит в столбец с фильтрами, и
 * потолок в 420px делал его уже соседних селектов — три контрола одного
 * назначения читались как разные. С `md` поиск встаёт с ними в строку, и
 * потолок возвращается, чтобы он не съедал её целиком.
 */
export const container = style({
  width: '100%',
  ...media({
    md: { maxWidth: rem(420) },
  }),
})

export const icon = style({
  fontSize: rem(18),
})

/**
 * Спиннер на месте лупы, пока идёт поиск.
 *
 * Именно на месте, а не рядом: иконка и спиннер одного размера, поэтому поле
 * не меняет раскладку, и занятость видна там, куда человек и так смотрит —
 * в поле, в которое печатает. Заменять кнопку очистки нельзя: она исчезала бы
 * ровно в тот момент, когда набранное хочется стереть.
 *
 * Цвет приглушённый: спиннер наследует `currentColor`, а в поле это цвет
 * текста, и на полном контрасте он перетягивал бы внимание с самого ввода.
 *
 * Коробка ровно под лупу (18px), а спиннер внутри свой (16px) и центрован:
 * так подмена не меняет ширину префикса и не сдвигает текст в поле на пару
 * пикселей. Задавать спиннеру размер классом снаружи нельзя — он спорил бы с
 * его собственным вариантом размера по порядку правил в бандле.
 */
export const spinner = style({
  display: 'inline-flex',
  alignItems: 'center',
  justifyContent: 'center',
  width: rem(18),
  height: rem(18),
  color: color.text('muted'),
})

/** Кнопка очистки подтянута к правому краю поля. */
export const clear = style({
  marginRight: calc(vars.space.xs).negate().toString(),
})

/** Форма нужна только ради клавиши «Найти» — в раскладке её быть не должно. */
export const form = style({
  display: 'contents',
})
