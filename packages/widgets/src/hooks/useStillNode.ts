import { useCallback } from 'react'

/**
 * Снимает начальный кадр Motion, который сервер напечатал в разметку, с узла
 * неподвижной ветки — той, что рендерится при `prefers-reduced-motion`.
 *
 * Зачем это вообще нужно. На сервере `useReducedMotion()` всегда возвращает
 * `false`, поэтому в HTML уезжает motion-ветка вместе со своим начальным
 * состоянием: `opacity:0;transform:translateY(24px)` у секции (`Reveal`),
 * `transform: translateY(96px)` у слоя параллакса (`DecorField`, `Parallax`,
 * уход героя). На клиенте с включённым сокращением движения компонент
 * рендерит неподвижную ветку — и этого **недостаточно**: React при гидратации
 * не приводит атрибуты существующего узла к клиентскому рендеру, поэтому
 * серверный инлайновый `style` остаётся висеть. Перебить его классом нельзя
 * (инлайн сильнее), задать `style` пропом — тоже: при гидратации он не
 * применяется.
 *
 * Замерено до правки: у человека с «уменьшить движение» вся главная ниже
 * героя оставалась прозрачной навсегда — 56 скрытых узлов после полной
 * прокрутки против 1 в обычном режиме.
 *
 * Поэтому свойства снимаются здесь, в ref-колбэке: он вызывается в коммите,
 * то есть уже после гидратации. Именно **снимаются** (пустая строка), а не
 * перебиваются значением: узел должен вернуться к тому, что говорит про него
 * CSS, а не получить ещё один инлайновый стиль поверх чужого.
 */
export const useStillNode = (): ((node: HTMLElement | null) => void) =>
  useCallback((node: HTMLElement | null): void => {
    if (node === null) {
      return
    }

    node.style.opacity = ''
    node.style.transform = ''
  }, [])
