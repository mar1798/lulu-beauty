import { style } from '@vanilla-extract/css'
import { media, rem } from 'widgets/styling/lib'
import { flexColumn, flexRow } from 'widgets/styling/mixin'

/**
 * Блок фильтров витрины: категория и бренд.
 *
 * Живёт в приложении, а не в `widgets`: `CatalogTemplate` держит фильтры одним
 * слотом и не знает, сколько их и какие они, — из чего этот слот собран,
 * решает страница.
 */

/**
 * До `md` — столбцом во всю ширину, дальше парой рядом.
 *
 * Именно `md`, а не `sm`: с `md` шаблон каталога ставит фильтры в одну строку
 * с поиском (`CatalogTemplate.controls`), и до этого момента все три контрола
 * должны быть одной ширины — иначе на промежуточных экранах два узких селекта
 * стояли рядом, а поиск под ними шёл во всю ширину.
 */
export const filters = style({
  ...flexColumn(16),
  ...media({
    md: {
      ...flexRow(16),
      alignItems: 'flex-end',
    },
  }),
})

/**
 * Фиксированная ширина полей на широком экране: тянуться во всю колонку им
 * незачем — рядом стоит поиск, и растянутые фильтры спорили бы с ним за
 * внимание. До `md` ограничения нет, там они в один столбец.
 */
export const field = style({
  ...media({
    md: {
      width: rem(220),
    },
  }),
})
