import { style } from '@vanilla-extract/css'
import { media, rem } from 'widgets/styling/lib'
import { flexColumn, flexRow } from 'widgets/styling/mixin'

/**
 * Блок фильтров витрины: категория и бренд.
 *
 * Живёт в приложении, а не в `widgets`: `CatalogTemplate` держит фильтры одним
 * слотом и не знает, сколько их и какие они, — из чего этот слот собран,
 * решает страница.
 */

/**
 * Блок фильтров витрины: категория, бренд и сортировка.
 *
 * До `md` — столбцом во всю ширину. С `md` — в строку, и до `xl` поля делят её
 * поровну: поиск в это время стоит строкой ниже во всю ширину
 * (`CatalogTemplate.controls`), и строка фильтров над ним должна быть той же
 * ширины, а не прижатой влево кучкой узких списков.
 */
export const filters = style({
  ...flexColumn(16),
  ...media({
    md: {
      ...flexRow(16),
      alignItems: 'flex-end',
    },
  }),
})

/**
 * Ширина поля. До `md` — во всю колонку (столбец), от `md` до `xl` — равная
 * доля строки, с `xl` — фиксированные 220px: там рядом встаёт поиск, и
 * растянутые фильтры спорили бы с ним за место и внимание.
 *
 * `minWidth: 0` — без него flex-элемент не ужимается уже своего содержимого,
 * и длинное название бренда в списке распирало бы строку.
 */
export const field = style({
  ...media({
    md: {
      flex: '1 1 0',
      minWidth: 0,
    },
    xl: {
      flex: 'none',
      width: rem(220),
    },
  }),
})

/**
 * Поиск витрины. От `md` до `xl` он стоит отдельной строкой под фильтрами, и
 * общий потолок `SearchField` в 420px оставлял бы справа пустую половину
 * строки — снимаем его до тех пор, пока поиск не встанет в ряд с фильтрами.
 *
 * `&&` удваивает класс: правило должно перебить собственный класс виджета,
 * а порядок стилевых файлов между пакетами — не то, на что стоит опираться.
 */
export const search = style({
  ...media({
    md: { selectors: { '&&': { maxWidth: 'none' } } },
    xl: { selectors: { '&&': { maxWidth: rem(420) } } },
  }),
})

/**
 * Форма пожелания под сеткой. Ограничена по ширине: это одно поле с двумя
 * подписями, и во всю колонку каталога оно выглядит как отдельная страница,
 * а строка ввода в 1200px читается хуже короткой.
 */
export const wanted = style({
  width: '100%',
  maxWidth: rem(680),
})
