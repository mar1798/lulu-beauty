import { style } from '@vanilla-extract/css'
import { rem } from 'widgets/styling/lib'
import { flexRow, focusVisibleRing } from 'widgets/styling/mixin'
import { vars } from 'widgets/styling/theme'

/** Ряд кнопок под сообщением: на узком экране переносится, а не сжимает подписи. */
export const actions = style({
  ...flexRow(12),
  flexWrap: 'wrap',
  marginTop: vars.space.xs,
})

/**
 * Область, содержимое которой известно только после ответа `/api/auth/me`:
 * корзина, избранное, вход.
 *
 * Все три страницы статические, поэтому первый кадр не знает, гость перед ним
 * или вошедший, и показывает одно, а через полсекунды — совсем другое по
 * высоте: «войдите» вместо списка. Подвал при этом уезжал, и это не придирка,
 * а худший CLS на сайте (0.394 на избранном, 0.208 на входе — оба в красной
 * зоне).
 *
 * Экран целиком, а не «примерно столько, сколько нужно»: подвал обязан
 * оказаться за нижней кромкой в **любом** из состояний, иначе он въезжает в
 * кадр на том, которое короче, и сдвиг засчитывается. Пустого места это не
 * добавляет — `BaseLayout` и так растягивает содержимое на высоту окна.
 *
 * Вешать резерв надо на обёртку **вокруг** карточки, а не внутрь неё: внутри он
 * растягивает и саму карточку, и под содержимым остаётся пустая треть экрана в
 * рамке (так было на `/login`). Снаружи он только центрирует карточку по высоте.
 */
export const sessionArea = style({
  minHeight: '100vh',
})

/**
 * Иконка внутри строки текста — сердце в подсказке пустого избранного.
 *
 * Иконки набора рисуются размером `1em`, то есть подстраиваются под текст сами;
 * поправлять остаётся только базовую линию: без сдвига сердце садится на неё
 * нижним углом и заметно всплывает над строкой.
 */
export const inlineIcon = style({
  verticalAlign: '-0.15em',
})

/**
 * Ссылка внутри строки текста врезки (`Alert`).
 *
 * Цвет наследуется от тона врезки — свой акцентный спорил бы с её рамкой и
 * фоном, — поэтому отличать ссылку от текста приходится подчёркиванием и
 * насыщенностью: одного цвета там нет вовсе, и без них она сливается.
 */
export const alertLink = style([
  {
    fontWeight: 500,
    textDecoration: 'underline',
    textUnderlineOffset: rem(3),
  },
  focusVisibleRing(),
])

/**
 * Подборщик на экране успеха: без внутреннего отступа, которым он отделяется
 * от состава на шаге оформления.
 *
 * Там он врезка внутри карточки состава, здесь — самостоятельный блок в потоке
 * страницы, и подложка с отступом читалась бы вторым, вложенным экраном под
 * врезкой «Заявка принята». Фон снимается вместе с отступом: без него подложка
 * обжимает содержимое вплотную и превращается в обрезок.
 */
export const flushPicker = style({
  padding: 0,
  backgroundColor: 'transparent',
})
