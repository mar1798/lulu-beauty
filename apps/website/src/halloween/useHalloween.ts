import { useSyncExternalStore } from 'react'
import { isHalloweenSeason } from './config'

const subscribe = (): (() => void) => () => undefined

/**
 * Идёт ли сейчас сезон оформления.
 *
 * На сервере и при гидрации — всегда `false`, в браузере сразу после неё —
 * настоящее значение по часам. Иначе нельзя: страницы статические, собраны
 * когда угодно, и ответ сборки разошёлся бы с ответом браузера после
 * `HALLOWEEN_UNTIL` — React получил бы другую разметку, чем пришла в HTML.
 *
 * Сцены поэтому появляются после гидрации, а не в первом кадре. Для декора
 * это даже лучше: он не спорит за загрузку с первым экраном и не становится
 * LCP-элементом. Сдвига нет — все сцены абсолютные и места в потоке не
 * занимают. А то, что должно быть в первом кадре (фон, паутинки на
 * карточках), держится на атрибуте `<html>`, который ставит ранний скрипт.
 */
export const useHalloween = (): boolean =>
  useSyncExternalStore(subscribe, isHalloweenSeason, () => false)
