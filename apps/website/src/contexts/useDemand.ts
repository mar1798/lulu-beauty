import { useCallback, useState } from 'react'

/**
 * Спрос на данные провайдера: есть ли на экране хоть кто-то, кому они нужны.
 *
 * `CartProvider` и `WishlistProvider` смонтированы в `_app.tsx`, то есть на
 * всех страницах сразу, — и запрашивали корзину с избранным тоже на всех,
 * включая админку, где ни того, ни другого не видно. Два лишних запроса на
 * каждой странице раздела, и оба уходили второй волной, после `/api/auth/me`.
 *
 * Провайдеры остаются там же, где были (состояние обязано переживать переходы
 * между страницами), но запрос уходит только после того, как кто-то реально
 * подписался — то есть вызвал `useCart`/`useWishlist`. Шапка витрины
 * подписывается всегда (в ней счётчик корзины), у админки шапка своя.
 *
 * Счётчик, а не флаг: потребителей на странице десятки (каждая карточка
 * каталога — это `AddToCartButton` и `WishlistButton`), и уход одного не
 * означает, что данные больше не нужны.
 */
export interface IDemand {
  /** Есть ли сейчас хоть один потребитель: по нему провайдер решает, делать ли запрос. */
  isWanted: boolean
  /**
   * Подписка потребителя. Возвращает отписку, поэтому эффекту достаточно её
   * вернуть: `useEffect(() => subscribe(), [subscribe])`.
   */
  subscribe: () => () => void
}

export const useDemand = (): IDemand => {
  const [count, setCount] = useState(0)

  /*
    Ссылка постоянная: она уезжает в значение контекста и попадает в зависимости
    эффекта у каждого потребителя — пересоздание перезаписывало бы всех
    подписчиков на каждый рендер провайдера.
  */
  const subscribe = useCallback((): (() => void) => {
    setCount(previous => previous + 1)

    return () => setCount(previous => previous - 1)
  }, [])

  return { isWanted: count > 0, subscribe }
}
