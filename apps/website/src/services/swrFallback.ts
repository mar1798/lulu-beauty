import { unstable_serialize, type Key } from 'swr'
import type { IOrderCycle } from 'widgets/types'
import { activeCycleKey } from './swrKeys'

/**
 * Наполнение кеша SWR данными, посчитанными на сборке.
 *
 * Возвращается страницей как `props.fallback`, а `_app.tsx` отдаёт его в
 * `SWRConfig`. Так значение достаётся **любому** компоненту по ключу, а не
 * только тому, кому его передали пропсом: кнопок «в корзину» на витрине два
 * десятка, и протаскивать сбор в каждую через `ProductGrid` пришлось бы
 * отдельным пропом ради того же самого.
 *
 * Ключи здесь — строки: `useSWR` принимает кортежи, но `fallback` ищет по
 * сериализованному виду, поэтому `unstable_serialize` обязателен (иначе запись
 * просто не найдётся, молча и без ошибки).
 */
export type ISwrFallback = Record<string, unknown>

/**
 * Когда посчитано то, что лежит в `fallback`. Ключ — не ключ SWR: `useSWR` по
 * нему никогда не спросит, он нужен только `isFreshFallback` ниже.
 */
const RENDERED_AT = '$renderedAt'

/**
 * Сколько значение из статики считается свежим. Столько же, сколько
 * `revalidate` у страниц со сбором: моложе этого пересборка ничего нового бы
 * не принесла.
 */
const FRESH_MS = 60_000

/**
 * Статика знает состояние сбора на момент сборки — этого хватает, чтобы
 * витрина отрисовалась сразу правильной. Без этого «приём заказов закрыт»
 * приезжает через сотню миллисекунд после первого кадра и сдвигает сетку, а
 * кнопки успевают мигнуть доступными.
 *
 * Рядом кладётся время рендера — по нему `isFreshFallback` решает, можно ли
 * этому значению верить без перепроверки.
 */
export const activeCycleFallback = (cycle: IOrderCycle | null): ISwrFallback => ({
  [unstable_serialize(activeCycleKey)]: cycle,
  [RENDERED_AT]: Date.now(),
})

/**
 * Лежит ли значение по этому ключу в `fallback` текущей страницы — и настолько
 * ли оно свежее, чтобы **не** перепроверять его при монтировании.
 *
 * `fallback` по умолчанию ревалидируется, и статика, аккуратно уложенная в
 * `getStaticProps`, уезжала повторным запросом сразу после гидратации — на
 * холодном заходе в одну секунду с `/api/auth/me`. Для только что собранной
 * страницы этот запрос и правда лишний.
 *
 * Но «страница не старше `revalidate`» — неправда. ISR отдаёт протухшую копию
 * **сразу**, а пересобирает её только в фоне: первый посетитель товара, на
 * который неделю никто не заходил, получает HTML недельной давности — со
 * сбором, который тогда был закрыт. Без перепроверки кнопка «в корзину» так и
 * оставалась погашенной до перезагрузки (на проде, 09.2026). Поэтому верим
 * только значению моложе `FRESH_MS`, всё прочее SWR перечитывает сам.
 *
 * Отрицательный возраст — часы клиента отстают от сервера, и сколько на самом
 * деле лет странице, не узнать; такое тоже перепроверяется.
 *
 * Проверка ключа — по сериализованному виду: `SWRConfig` хранит `fallback`
 * строками (см. `unstable_serialize` выше).
 */
export const isFreshFallback = (fallback: ISwrFallback | undefined, key: Key): boolean =>
  fallback !== undefined && unstable_serialize(key) in fallback && isFreshRender(fallback)

/**
 * Собрана ли статика текущей страницы моложе `FRESH_MS` назад — для данных,
 * которые страница отдаёт не через `fallback`, а пропсами (первая страница
 * каталога в `pages/catalog/index.tsx`): они протухают вместе с ней.
 */
export const isFreshRender = (fallback: ISwrFallback | undefined): boolean => {
  const renderedAt = fallback?.[RENDERED_AT]

  if (typeof renderedAt !== 'number') {
    return false
  }

  const age = Date.now() - renderedAt

  return age >= 0 && age < FRESH_MS
}
